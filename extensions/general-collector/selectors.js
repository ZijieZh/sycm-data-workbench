  /**
   * ⭐ 指标列的**分组前缀**规则（`colGroupOfHeader` 的唯一实现）。
   *
   * 平台导出表头里两种带分隔符的形态，**必须区分开**（混了就错）：
   *   ① **组名前缀列**：`<组名>·<指标名>` —— 同一指标在多个分组下重复出现，每列各占一列。
   *      实测：人群分类 分日 的 22 个指标列 = `整体·`5 列 + `新客·`3 + `老客·`7 + `未购新客·`3 + `已购新客·`4。
   *      → 勾选全部指标后，**每组汇总列都已包含在这 22 列里，不额外多列**。
   *   ② **指标名自带连字符**：`收藏商品-支付买家数`、`下单-支付转化率` —— 那不是分组前缀，
   *      是**指标本名**（实测：整体 分日 119 列里就有 3 个这样的名字，全是独立指标）。
   *
   * 因此分组前缀**只认 `·` 与 `|`**，不认 `-`：宁可少切（保守）也不能把指标名切坏。
   * 旧版本曾把 `-` 当分隔符 → `收藏商品-支付买家数` 会被误切成组名/指标名两个"指标"，
   * 导致依赖表头重建列数的调用方**少算/多算**。
   */
  const HEADER_GROUP_SEPARATOR = '·';
  const HEADER_GROUP_SEPARATOR_ALT = '|';
  const HEADER_GROUP_PATTERN = /^(.+?)[·|](.+)$/;

  /** 表头单元格 → 分组名；没有分组前缀时返回 ''（**不返回 null**：'' = 无前缀，null = 非字符串输入）。 */
  function colGroupOfHeader(headerCell) {
    if (headerCell == null) return null;
    const text = String(headerCell).trim();
    if (!text) return '';
    const m = HEADER_GROUP_PATTERN.exec(text);
    return m ? m[1].trim() : '';
  }

  /** 表头单元格 → 去掉分组前缀的指标名（无前缀时原样返回）。 */
  function colMetricOfHeader(headerCell) {
    if (headerCell == null) return null;
    const text = String(headerCell).trim();
    const m = HEADER_GROUP_PATTERN.exec(text);
    return m ? m[2].trim() : text;
  }

  /** 从一组表头里解析出「分组名 → 列数」；`__ungrouped__` = 无前缀的指标列。 */
  function parseHeaderGroups(headers) {
    const list = Array.isArray(headers) ? headers : [];
    const groups = {};
    for (const cell of list) {
      const name = colGroupOfHeader(cell);
      if (name == null) continue;
      const key = name === '' ? '__ungrouped__' : name;
      groups[key] = (groups[key] || 0) + 1;
    }
    return groups;
  }

